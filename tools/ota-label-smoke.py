# Layout and rejection messages come from wled00/wled_metadata.{h,cpp}.
def label_hash(label):
    """Compute the metadata sanity hash for the ASCII test labels."""
    result = 5381
    for byte in label:
        result = (result * 33 + byte) & 0xFFFFFFFF
    return result


def upload(device, firmware):
    """Submit the ordinary update form with validation enabled."""
    boundary = "----WledOtaTest" + uuid.uuid4().hex
    body = (
        f'--{boundary}\r\nContent-Disposition: form-data; name="update"; '
        'filename="firmware.bin"\r\nContent-Type: application/octet-stream\r\n\r\n'
    ).encode() + firmware + f"\r\n--{boundary}--\r\n".encode()
    request = urllib.request.Request(
        device + "/update", data=body,
        headers={"Content-Type": "multipart/form-data; boundary=" + boundary},
    )
    try:
        with urllib.request.urlopen(request, timeout=60) as response:
            return response.status, response.read().decode(errors="replace")
    except urllib.error.HTTPError as error:
        return error.code, error.read().decode(errors="replace")


def main():
    """Check negative cases before installing the unmodified matching image."""
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--device", required=True)
    parser.add_argument("--firmware", required=True, type=Path)
    parser.add_argument("--upload", required=True, action="store_true",
                        help="acknowledge that this test installs firmware and reboots")
    args = parser.parse_args()
    device = args.device.rstrip("/")
    firmware = args.firmware.read_bytes()
    if not firmware or firmware[0] != 0xE9:
        raise SystemExit("Expected an ESP32 application image")
    offset = firmware[:768].find(struct.pack("<I", 0x57535453))
    if offset < 0 or offset + 111 > len(firmware):
        raise SystemExit("No complete WLED metadata in the application header")
    label = firmware[offset + 56:offset + 104].split(b"\0", 1)[0]
    with urllib.request.urlopen(device + "/json/info", timeout=10) as response:
        info = json.load(response)
    if label.decode("ascii") != info.get("release"):
        raise SystemExit("Use firmware with the same release label as the running device")

    cases = []
    mismatch = bytearray(firmware)
    wrong_label = b"OTA_LABEL_MISMATCH"
    mismatch[offset + 56:offset + 104] = wrong_label.ljust(48, b"\0")
    struct.pack_into("<I", mismatch, offset + 104, label_hash(wrong_label))
    cases.append(("different label", mismatch, "uploaded='OTA_LABEL_MISMATCH'."))
    unterminated = bytearray(firmware)
    unterminated[offset + 56:offset + 104] = b"A" * 48
    cases.append(("unterminated label", unterminated, "missing compatibility metadata"))
    bad_hash = bytearray(firmware)
    bad_hash[offset + 104] ^= 1
    cases.append(("invalid metadata hash", bad_hash, "missing compatibility metadata"))
    unsafe_version = bytearray(firmware)
    struct.pack_into("<I", unsafe_version, offset + 4, 2)
    unsafe_version[offset + 108:offset + 111] = bytes([255, 0, 0])
    cases.append(("minimum version", unsafe_version, "Cannot update from this version"))
    for name, image, expected in cases:
        status, response = upload(device, image)
        if status != 500 or expected not in response:
            raise SystemExit(f"FAIL {name}: HTTP {status}, expected compatibility rejection")
        print(f"PASS rejected {name}", flush=True)

    status, response = upload(device, firmware)
    if status != 200 or "Update successful" not in response:
        raise SystemExit(f"FAIL matching label: HTTP {status}")
    print("PASS matching label: normal OTA accepted; verify reboot and device status", flush=True)


if __name__ == "__main__":
    main()
