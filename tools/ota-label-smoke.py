"""Exercise the real ESP32 OTA validator, then install a matching application image.

Run against a device already containing the parser fix:
  python tools/ota-label-smoke.py --device http://192.168.71.71 \
      --firmware path/to/firmware.bin --upload

This test uploads firmware and reboots the device. Use an application .bin for
the device's exact hardware and release label, not a merged/factory image.
No validation-bypass option is sent. Malformed images must be rejected by the
compatibility check; their image checksums are deliberately not repaired.
"""

import argparse
import json
from pathlib import Path
import struct
import urllib.error
import urllib.request
import uuid


